def events_parts(pkg):
    """(header lines, source lines) for the package's events."""
    p = pkg.name
    H = []
    if pkg.types:
        H.append("/* types */")
        H += [t if t.rstrip().endswith((";", "}")) or t.lstrip().startswith("#") else t + ";" for t in pkg.types]
        H.append("")
    if pkg.events:
        H.append("/* events */")
    for i, e in enumerate(pkg.events, 1):
        H.append(f"#define {cident(e.name)}_{p}_id {i}")
    for e in pkg.events:
        en = cident(e.name)
        sig = ", ".join(f"{a.type} p_{a.name}" for a in e.args)
        H += ["", f"/*## event {e.name}({', '.join(a.type for a in e.args)}) */",
              f"typedef struct {en} {en};", f"struct {en} {{", "    RiCEvent ric_event;"]
        H += [f"    {a.type} {a.name};" for a in e.args]
        H += ["};", f"{en} * RiC_Create_{en}({sig or 'void'});"]
    if pkg.events:
        H += ["", f"void {p}_eventsInit(void);", ""]

    C = []
    if pkg.events:
        C += ["/* ---- events ---- */", "typedef union {", "    RiCEvent base_;"]
        C += [f"    {cident(e.name)} {cident(e.name)}_;" for e in pkg.events]
        C += [f"}} {p}_AnyEvent;", f"static {p}_AnyEvent {p}_eventPool[RIC_EVENT_POOL_SIZE];", "",
              f"static const char * {p}_eventName(RiCEventId id) {{", "    switch (id) {"]
        C += [f'        case {cident(e.name)}_{p}_id: return "{e.name}";' for e in pkg.events]
        C += ['        default: return "?";', "    }", "}", "",
              "/* registers the event pool once; called from every class's _Init */",
              f"void {p}_eventsInit(void) {{", "    static RiCBoolean done = RiCFALSE;", "    if (done)",
              "        return;", "    done = RiCTRUE;",
              f"    RiCEventPool_register({p}_eventPool, sizeof({p}_AnyEvent), RIC_EVENT_POOL_SIZE);",
              f"    RiCOXF_eventNameHook = {p}_eventName;", "}", ""]
    for e in pkg.events:
        en = cident(e.name)
        sig = ", ".join(f"{a.type} p_{a.name}" for a in e.args)
        C += [f"{en} * RiC_Create_{en}({sig or 'void'}) {{",
              f"    {en}* me = ({en} *)RiCEventPool_alloc();",
              "    if (me != NULL) {",
              f"        RiCEvent_init(&me->ric_event, {en}_{p}_id);"]
        C += [f"        me->{a.name} = p_{a.name};" for a in e.args]
        C += ["    }", "    return me;", "}", ""]
    return H, C


def ctype_kind(t):
    t = t.replace("const", "").strip()
    if any(k in t for k in ("float", "double")):
        return "f"
    if "*" in t:
        return "s" if "char" in t else None
    return "i"


def sim_main(pkg, gens):
    """PC simulation driver: reads commands from stdin.
       <event> [args]  |  <instance>.<event> [args]  |  tick <ms>  |  state  |  quit"""
    p = pkg.name
    live = [g for g in gens if g.m]
    L = [BANNER.format(elem=p, file=SIM_MAIN),
         "/* PC simulation driver. Commands on stdin, one per line:",
         " *   evStart 5          send an event (to the first instance that handles it)",
         " *   itsOven.evStart 5  send to a specific instance",
         " *   tick 500           advance time by 500 ms (1 ms steps)",
         " *   state              print active states",
         " *   quit",
         " * Lines starting with '@' are machine readable (used by the web editor). */",
         "#ifndef _CRT_SECURE_NO_WARNINGS", "#define _CRT_SECURE_NO_WARNINGS", "#endif",
         "#include <stdio.h>", "#include <stdlib.h>", "#include <string.h>"]
    L += [f'#include "{g.n}.h"' for g in gens]
    L.append("")
    for g in live:
        L.append(f"static {g.n} its{g.n};")
    L += ["", "static void trace(const RiCReactive *who, int kind, const char *what) {",
          '    static const char *const k[] = { "enter", "exit", "event", "drop", "trans" };',
          '    printf("@trace %lu %s %s %s\\n", (unsigned long)RiCOXF_now(), who ? who->name : "-", k[kind], what);',
          "}", "", "static void printState(void) {"]
    for g in live:
        L.append(f'    printf("@state its{g.n}");')
        for s in g.states[1:]:
            if not composite(s):
                L.append(f'    if ({g.n}_isIn(&its{g.n}, {g.E(s)})) printf(" {s.name}");')
        L.append('    printf("\\n");')
    if not live:
        L.append('    printf("@state\\n");')
    L += ["}", "", "static int send(const char *inst, const char *ev, char *args) {",
          "    char *a[8];", "    int na = 0;", "    char *tok = strtok(args, \" \\t,\");",
          "    while (tok && na < 8) { a[na++] = tok; tok = strtok(NULL, \" \\t,\"); }"]
    for e in pkg.events:
        en = cident(e.name)
        receivers = [g for g in live if any(t.event == e.name for t in g.m.transitions)] or live
        if e.triggered:
            receivers = [g for g in live if g.n == e.triggered]
            if not receivers:
                continue
        conv, ok = [], True
        for i, a in enumerate(e.args):
            k = ctype_kind(a.type)
            if k == "i":
                conv.append(f"na > {i} ? ({a.type})strtol(a[{i}], NULL, 0) : ({a.type})0")
            elif k == "f":
                conv.append(f"na > {i} ? ({a.type})strtod(a[{i}], NULL) : ({a.type})0")
            elif k == "s":
                conv.append(f'na > {i} ? a[{i}] : ""')
            else:
                ok = False
        if not ok:
            continue
        L.append(f'    if (strcmp(ev, "{e.name}") == 0) {{')
        for gi, g in enumerate(receivers):
            cond = f'(!inst || strcmp(inst, "its{g.n}") == 0)'
            L.append(f"        {'if' if gi == 0 else 'else if'} {cond}")
            if e.triggered:
                if e.triggered != g.n:
                    continue
                L.append(f"            {{ {g.n}_{en}(&its{g.n}{''.join(', ' + c for c in conv)}); return 1; }}")
            else:
                L.append(f"            return RiCGEN(&its{g.n}, {en}({', '.join(conv)})) ? 1 : -1;")
        L += ["        return 0;", "    }"]
    L += ["    (void)inst; (void)a; (void)na;", "    return 0;", "}", "",
          "int main(void) {", "    char line[256];",
          "    RiCOXF_Init();", "    RiCOXF_traceHook = trace;"]
    for g in live:
        L.append(f"    {g.n}_Init(&its{g.n}, RiCOXF_mainTask());")
        L.append(f'    RiCReactive_setName(&its{g.n}.ric_reactive, "its{g.n}");')
    for g in gens:
        for a in g.c.assocs:
            if any(x.n == a.other for x in live) and g.m:
                L.append(f"    its{g.n}.{a.name} = &its{a.other};")
    for g in live:
        L.append(f"    {g.n}_startBehavior(&its{g.n});")
    L += ["    RiCOXF_processEvents();", "    printState();", '    printf("@end\\n");', "    fflush(stdout);",
          "    while (fgets(line, sizeof line, stdin)) {",
          "        char *cmd = strtok(line, \" \\t\\r\\n\");",
          "        char *rest = strtok(NULL, \"\\r\\n\");",
          "        if (!cmd) continue;",
          '        if (strcmp(cmd, "quit") == 0) break;',
          '        if (strcmp(cmd, "tick") == 0) {',
          "            long ms = rest ? strtol(rest, NULL, 0) : 1;",
          "            while (ms-- > 0) { RiCOXF_tick(1); RiCOXF_processEvents(); }",
          '        } else if (strcmp(cmd, "state") != 0) {',
          '            char *dot = strchr(cmd, \'.\');',
          "            char *inst = NULL;",
          "            int r;",
          "            char empty[1] = \"\";",
          "            if (dot) { *dot = 0; inst = cmd; cmd = dot + 1; }",
          "            r = send(inst, cmd, rest ? rest : empty);",
          '            if (r == 0) printf("@error unknown event %s\\n", cmd);',
          '            else if (r < 0) printf("@error event pool or queue full\\n");',
          "            RiCOXF_processEvents();",
          "        }",
          "        printState();",
          '        printf("@end\\n");',
          "        fflush(stdout);",
          "    }",
          "    return 0;", "}", ""]
    return "\n".join(L)


def target_main(pkg, gens):
    live = [g for g in gens if g.m]
    L = [BANNER.format(elem=pkg.name, file=TARGET_MAIN),
         "/* Main loop example for a microcontroller.",
         " * Build flags: -DRIC_NO_STDIO -DRIC_NO_TRACE (no printf / trace strings).",
         " * If events are sent or RiCOXF_tick() is called from interrupts, define",
         " * RIC_CRITICAL_ENTER() / RIC_CRITICAL_EXIT() as interrupt disable / enable. */"]
    L += [f'#include "{g.n}.h"' for g in gens]
    L.append("")
    for g in live:
        L.append(f"static {g.n} its{g.n};")
    L += ["", "/* call every 1 ms from a timer interrupt (e.g. SysTick_Handler) */",
          "void RiC_SysTick(void) {", "    RiCOXF_tick(1);", "}", "",
          "int main(void) {", "    /* board / clock / timer init here */", "    RiCOXF_Init();"]
    for g in live:
        L.append(f"    {g.n}_Init(&its{g.n}, RiCOXF_mainTask());")
    for g in gens:
        for a in g.c.assocs:
            if any(x.n == a.other for x in live) and g.m:
                L.append(f"    its{g.n}.{a.name} = &its{a.other};")
    for g in live:
        L.append(f"    {g.n}_startBehavior(&its{g.n});")
    noargs = {e.name for e in pkg.events if not e.args}
    ex = next((f"RiCGEN(&its{g.n}, {cident(t.event)}())" for g in live for t in g.m.transitions
               if t.event in noargs), "RiCGEN(&itsX, evY())")
    L += ["    for (;;) {", "        RiCOXF_processEvents();",
          f"        /* read inputs here, e.g.  if (button()) {ex}; */", "    }", "}", ""]
    return "\n".join(L)


UT_HEADER = """/* ut.h - helpers for unit tests of the generated code */
#ifndef UT_H
#define UT_H
#include <stdio.h>
#include "RiCLite.h"

static int ut_failed;
#define CHECK(cond) do { if (cond) printf("  ok    %s\\n", #cond); \\
                         else { printf("  FAIL  %s   (line %d)\\n", #cond, __LINE__); ut_failed++; } } while (0)

static void UT_init(void) { RiCOXF_Init(); }                  /* start the framework     */
static void UT_run(void) { RiCOXF_processEvents(); }          /* handle queued events     */
static void UT_tick(unsigned long ms)                         /* let ms milliseconds pass */
{
    while (ms--) { RiCOXF_tick(1); RiCOXF_processEvents(); }
}
static int UT_report(void)
{
    printf(ut_failed ? "\\n%d check(s) failed\\n" : "\\nall checks passed\\n", ut_failed);
    return ut_failed != 0;
}
#endif
"""


def _first_leaf(state):
    s = state
    while s.children and not s.is_and:
        t = s.initial.dst if s.initial is not None else (s.children[0] if len(s.children) == 1 else None)
        if not isinstance(t, State):
            return None
        s = t
    return None if s.is_and else s


def test_file(pkg, gens):
    """an example unit test that walks the first plain transitions of the first chart"""
    live = [g for g in gens if g.m]
    p = pkg.name
    L = [f"/* test_{p}.c - unit tests for the generated code. A starting point: change it freely.",
         " *",
         " *   RiCGEN(&obj, evName(args));  send an event (as in Rhapsody), then UT_run() to handle it",
         " *   obj_opName(&obj, args);      triggered operation: handled right away",
         " *   UT_tick(ms);                 let time pass (tm() transitions)",
         " *   CHECK(IS_IN(&obj, Class_STATE));  CHECK(obj.variable == 3);", " */",
         '#include "ut.h"']
    L += [f'#include "{g.n}.h"' for g in gens]
    L += [""] + [f"static {g.n} its{g.n};" for g in live] + ["", "int main(void) {", "    UT_init();"]
    L += [f"    {g.n}_Init(&its{g.n}, RiCOXF_mainTask());" for g in live]
    for g in gens:
        for a in g.c.assocs:
            if any(x.n == a.other for x in live) and g.m:
                L.append(f"    its{g.n}.{a.name} = &its{a.other};")
    L += [f"    {g.n}_startBehavior(&its{g.n});" for g in live]
    if live:
        L.append("    UT_run();")
        g = live[0]
        obj = f"its{g.n}"
        cur = _first_leaf(g.m.root)
        if cur is not None:
            L += ["", '    printf("start\\n");', f"    CHECK(IS_IN(&{obj}, {g.E(cur)}));\t/* the default transition enters {cur.name} */"]
            seen = {cur}
            for _ in range(4):
                step, s = None, cur
                while s is not None and step is None:
                    for t in g.by_src.get(s, []):
                        if not t.internal and not t.guard.strip() and isinstance(t.dst, State) and \
                                (t.event or re.fullmatch(r"\s*\d+\s*", t.timeout or "")):
                            step = t
                            break
                    s = s.parent
                if step is None:
                    break
                nxt = _first_leaf(step.dst)
                if nxt is None:
                    break
                e = g.ev.get(step.event) if step.event else None
                if step.event and e is not None and e.triggered:
                    args = "".join(", 0" for _ in e.args)
                    call, why = [f"    {g.n}_{cident(step.event)}(&{obj}{args});\t/* triggered operation */"], step.event
                elif step.event:
                    args = ", ".join("0" for _ in (e.args if e else []))
                    call, why = [f"    RiCGEN(&{obj}, {cident(step.event)}({args}));", "    UT_run();"], step.event
                else:
                    call, why = [f"    UT_tick({step.timeout.strip()});"], f"tm({step.timeout.strip()})"
                L += ["", f'    printf("{why}\\n");'] + call + \
                     [f"    CHECK(IS_IN(&{obj}, {g.E(nxt)}));\t/* {cur.name} --{why}--> {nxt.name} */"]
                if nxt in seen:
                    break
                seen.add(nxt)
                cur = nxt
        for a in g.c.attributes:
            if ctype_kind(a.type) == "i":
                L.append(f'    printf("  {a.name} = %ld\\n", (long){obj}.{a.name});')
    L += ["    return UT_report();", "}", ""]
    return "\n".join(L)


def generate(pkg, out, sim=True):
    """Write all sources to `out`. Returns ({file: text} the user needs, warnings);
    the simulator driver is written to disk but left out of the returned files."""
    os.makedirs(out, exist_ok=True)
    eh, ec = events_parts(pkg)
    single = len(pkg.classes) == 1
    files = {}
    if not single:
        p = pkg.name
        files[f"{p}.h"] = "\n".join([BANNER.format(elem=p, file=f"{p}.h"), f"#ifndef {p}_H", f"#define {p}_H", "",
                                     '#include "RiCLite.h"', ""] + eh + ["#endif", ""])
        files[f"{p}.c"] = "\n".join([BANNER.format(elem=p, file=f"{p}.c"), f'#include "{p}.h"', ""] + ec)
    warnings = list(pkg.warnings)
    gens = []
    for cls in pkg.classes:
        g = ClassGen(pkg, cls)
        gens.append(g)
        files[f"{cls.name}.h"] = g.header(eh if single else None)
        files[f"{cls.name}.c"] = g.source(ec if single else None)
        warnings += [f"{cls.name}: {w}" for w in g.warn]
    for fn in ("RiCLite.h", "RiCLite.c"):
        with open(os.path.join(RICL, fn), encoding="utf-8") as f:
            files[fn] = f.read()
    if sim:
        files[TARGET_MAIN] = target_main(pkg, gens)
    hidden = {SIM_MAIN: sim_main(pkg, gens), "ut.h": UT_HEADER} if sim else {}
    if sim:
        files[f"test_{pkg.name}.c"] = test_file(pkg, gens)
    for fn, text in {**files, **hidden}.items():
        with open(os.path.join(out, fn), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return files, warnings
