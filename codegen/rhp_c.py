"""Rhapsody-style C emitter for the statechart IR (sc_ir.Package).

Output per class, shaped like Rhapsody's flat C statechart code:

    struct X { RiCReactive ric_reactive; attributes; links; state variables };
    X_Init / X_Cleanup / X_startBehavior / X_isIn (+ X_<state>_IN macros)
    rootState_entDef          - initial entry
    rootState_dispatchEvent   - ONE function: nested switch over the active
                                state, inner states first, then their parents
    <S>_entDef / <S>_exit     - only for composite states (their content is
                                only known at run time); simple states are
                                entered and left inline, like Rhapsody does

Events (`struct evX { RiCEvent ric_event; args }`, `RiC_Create_evX()`) go
into the class files when the package has one class, otherwise into
<Pkg>.h/.c. Runs on RiCLite (ricl/) - static pools, no malloc, no recursion.

    from rhp_c import generate
    files, warnings = generate(pkg, out_dir)     # files: what the user gets
"""
import os
import re
import shutil

from sc_ir import AND, OR, Node, State, cident  # noqa: F401

RICL = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ricl")
BANNER = """/*********************************************************************
\tGenerated by sc2c (Rhapsody C style, RiCLite framework)
\tModel Element\t: {elem}
\tFile\t\t: {file}
*********************************************************************/
"""
SIM_MAIN = "sim_main.c"          # PC simulator driver (used by the editor, not shown)
TARGET_MAIN = "main.c"           # bare-metal main loop example


def ind(code, n):
    pad = " " * n
    return "\n".join(pad + ln if ln.strip() else "" for ln in code.splitlines())


_IS_IN1 = re.compile(r"\bIS_IN\s*\(\s*([A-Za-z_]\w*)\s*\)")


def user_code(code):
    """Accept the one-argument IS_IN(state) form too (Rhapsody C wants IS_IN(me, state))."""
    return _IS_IN1.sub(r"IS_IN(me, \1)", (code or "").strip())


SEND_CALL = re.compile(r"\b([A-Za-z_]\w*?)_(\w+)\s*\(\s*(me(?:->\w+)?|&\w+)\s*(?:,\s*([^()]*))?\)")


def user_block(code, n, tag):
    code = user_code(code)
    if not code:
        return []
    return [" " * n + f"/*#[ {tag} */", " " * n + "{", ind(code, n + 4), " " * n + "}", " " * n + "/*#]*/"]


def ancestors(s):
    out = []
    while s is not None:
        out.append(s)
        s = s.parent
    return out


def is_region(s):
    return s.parent is not None and s.parent.is_and


def composite(s):
    return s.kind in (OR, AND) or is_region(s)


class ClassGen:
    def __init__(self, pkg, cls):
        self.pkg, self.c, self.m = pkg, cls, cls.machine
        self.n = cls.name
        self.ev = {e.name: e for e in pkg.events}
        self.warn = []
        self.timeouts = {}            # Trans -> timeout id name
        self.timers_of = {}           # State -> [(timeout id name, delay expr)]; one timer per delay
        self.hist = {}                # State -> history Node
        self.uses_term = False
        if not self.m:
            return
        self.m.root.cname = "rootState"
        for t in self.m.transitions:
            if t.timeout and isinstance(t.src, State):
                lst = self.timers_of.setdefault(t.src, [])
                expr = t.timeout.strip()
                tid = next((i for i, e in lst if e == expr), None)
                if tid is None:
                    tid = f"{self.n}_Timeout_{t.src.cname}_id" + (f"_{len(lst)}" if lst else "")
                    lst.append((tid, expr))
                self.timeouts[t] = tid
        for nd in self.m.nodes:
            if nd.kind == "history" and nd.parent is not None:
                self.hist[nd.parent] = nd
            if nd.kind == "term":
                self.uses_term = True
        self.states = self.m.states()
        self.by_src = {}
        for t in self.m.transitions:
            if isinstance(t.src, State):
                self.by_src.setdefault(t.src, []).append(t)

    # ---- hooks: the parts that depend on the runtime (UT style overrides these) ----
    def ublock(self, code, n, tag):
        code = self.ucode(code)
        if not code:
            return []
        return [" " * n + f"/*#[ {tag} */", " " * n + "{", ind(code, n + 4), " " * n + "}", " " * n + "/*#]*/"]

    def ucode(self, code):
        """Action code may send events as plain calls - Motor_evRun(me->itsMotor, 1500),
        Led_evButton(me) - the same form the UT-style code offers. Here they become RiCGEN."""
        code = user_code(code)
        classes = {c.name for c in self.pkg.classes}
        events = {cident(e.name) for e in self.pkg.events}

        def send(m):
            cls, ev, target, args = m.group(1), m.group(2), m.group(3), (m.group(4) or "").strip()
            if cls not in classes or ev not in events:
                return m.group(0)
            return f"RiCGEN({target}, {ev}({args}))"
        return SEND_CALL.sub(send, code)

    def trace_trans(self, label):
        return f'RIC_TRACE(&me->ric_reactive, RIC_TR_TRANS, "{label}");'

    def trace_state(self, kind, name):
        return f'RIC_TRACE(&me->ric_reactive, RIC_TR_{kind}, "{name}");'

    def start_timer(self, tid, expr, name):
        return (f"RiCTask_schedTm(me->ric_reactive.myTask, (RiC_UINT32)({expr}), {tid}, "
                f'&me->ric_reactive, "tm@{name}");')

    def stop_timer(self, tid):
        return f"RiCTask_unschedTm(me->ric_reactive.myTask, {tid}, &me->ric_reactive);"

    def terminate_line(self):
        return "RiCReactive_terminate(&me->ric_reactive);"

    YES, NO, STATUS = "eventConsumed", "eventNotConsumed", "RiCTakeEventStatus"

    def none(self):
        return f"{self.n}_RiCNonState"

    def ev_test(self, trig):
        return f"id == {trig}"

    def tm_test(self, tid):
        return f"RiCTimeout_getTimeoutId((RiCTimeout *)me->ric_reactive.current_event) == {tid}"

    def params_lines(self, e):
        return [f"RiCSETPARAMS(me, {cident(e.name)});", "(void)params;"]

    # ---- naming ------------------------------------------------------------
    def E(self, s):
        return f"{self.n}_{s.cname}"                  # enum value

    def sub(self, s):
        return f"me->{s.cname}_subState"

    def has_sub(self, s):
        return s.parent is None or (composite(s) and not s.is_and)

    def nm(self, s):
        return s.name or "ROOT"

    def follow_diagram(self, node):
        if node.outgoing or node.kind != "diagram":
            return node
        for x in self.m.nodes:
            if x is not node and x.kind == "diagram" and x.name == node.name and x.outgoing:
                return x
        self.warn.append(f"diagram connector '{node.name}' has no partner")
        return node

    def domain(self, src, tgt):
        sa, ta = ancestors(src), ancestors(tgt)
        if tgt in sa:
            lca = tgt.parent
        elif src in ta:
            lca = src.parent
        else:
            lca = next(a for a in sa if a in ta)
        while lca is not None and lca.is_and:      # across regions: leave the AND state
            lca = lca.parent
        if lca is None:
            lca = self.m.root
        main = next((a for a in sa if a.parent is lca), src)
        return lca, main

    # ---- inline enter / exit of one state -------------------------------------
    def enter_lines(self, s, n):
        """Enter s itself (not its substates)."""
        if is_region(s):
            return []
        sp = " " * n
        L = []
        if not s.parent.is_and:
            L.append(sp + f"{self.sub(s.parent)} = {self.E(s)};")
        t = self.trace_state("ENTER", self.nm(s))
        if t:
            L.append(sp + t)
        L += self.ublock(s.entry, n, f"state {self.nm(s)}.(Entry)")
        for tid, expr in self.timers_of.get(s, []):
            L.append(sp + self.start_timer(tid, expr, self.nm(s)))
        return L

    def leave_lines(self, s, n):
        """Leave s itself, after its substates are gone."""
        if is_region(s):
            return []
        sp = " " * n
        L = [sp + self.stop_timer(tid)
             for tid, _ in self.timers_of.get(s, [])]
        L += self.ublock(s.exit, n, f"state {self.nm(s)}.(Exit)")
        t = self.trace_state("EXIT", self.nm(s))
        if t:
            L.append(sp + t)
        if not s.parent.is_and:
            L.append(sp + f"{self.sub(s.parent)} = {self.none()};")
        return L

    def exit_lines(self, s, n):
        """Leave s and everything active inside it."""
        if composite(s):
            return [" " * n + f"{s.cname}_exit(me);"]
        return self.leave_lines(s, n)

    def entdef_lines(self, s, n, hist=False):
        """Enter s and run its default transition(s)."""
        if hist and s in self.hist:
            return [" " * n + f"{s.cname}_histEntDef(me);"]
        if composite(s):
            return [" " * n + f"{s.cname}_entDef(me);"]
        return self.enter_lines(s, n)

    def enter_path(self, lca, target, hist, n):
        path, x = [], target
        while x is not None and x is not lca:
            path.insert(0, x)
            x = x.parent
        if x is None:
            self.warn.append(f"cannot enter '{target.name}' from '{self.nm(lca)}'")
            return []
        out = []

        def go(i):
            s = path[i]
            if i == len(path) - 1:
                out.extend(self.entdef_lines(s, n, hist))
                return
            out.extend(self.enter_lines(s, n))
            nxt = path[i + 1]
            if s.is_and:
                for r in s.children:
                    if r is nxt:
                        go(i + 1)
                    else:
                        out.extend(self.entdef_lines(r, n))
            else:
                go(i + 1)
        if path:
            go(0)
        return out

    # ---- compound transitions -----------------------------------------------
    def complete(self, mode, owner, dst, acts, n, label, var="res"):
        """Lines that finish a transition from `owner` to `dst`.
        mode 'trans': exits + actions + entries; 'init': default transition."""
        sp = " " * n
        if isinstance(dst, Node):
            dst = self.follow_diagram(dst)
            if dst.kind in ("cond", "junction") or (dst.kind == "diagram" and dst.outgoing):
                out, first = [], True
                for b in sorted(dst.outgoing, key=lambda b: b.guard.strip() == "else"):
                    g = self.ucode(b.guard)
                    if g == "else" or not g:
                        out.append(sp + ("else {" if not first else "{"))
                    else:
                        out.append(sp + f"{'if' if first else 'else if'} ({g}) {{")
                    out += self.complete(mode, owner, b.dst, acts + [b.action], n + 4, label, var)
                    out.append(sp + "}")
                    first = False
                    if g == "else" or not g:
                        break
                return out
            if dst.kind == "history":
                target, hist = dst.parent, True
            elif dst.kind == "term":
                out = []
                if mode == "trans":
                    out.append(sp + "rootState_exit(me);")
                for a in acts:
                    out += self.ublock(a, n, f"transition {label}")
                out.append(sp + self.terminate_line())
                if mode == "trans":
                    out.append(sp + f"{var} = {self.YES};")
                return out
            else:
                self.warn.append(f"unsupported connector '{dst.kind}' after '{owner.name}'")
                return [sp + "/* unsupported connector */"]
        else:
            target, hist = dst, False
        out = []
        if mode == "trans":
            lca, main = self.domain(owner, target)
            out += self.exit_lines(main, n)
        else:
            lca = owner
        out.append(sp + self.trace_trans(label))
        for a in acts:
            out += self.ublock(a, n, f"transition {label}")
        out += self.enter_path(lca, target, hist, n)
        if mode == "trans":
            out.append(sp + f"{var} = {self.YES};")
        return out

    def tname(self, x):
        if isinstance(x, State):
            return self.nm(x)
        if x.kind == "history":
            return f"{x.parent.name}.H"
        return x.kind

    def default_code(self, s, n):
        if s.initial is not None:
            return self.complete("init", s, s.initial.dst, [s.initial.action], n,
                                 f"{self.nm(s)}>{self.tname(s.initial.dst)}")
        kids = s.children
        if len(kids) == 1 and not s.is_and:
            self.warn.append(f"'{self.nm(s)}' has no default transition; entering its only substate")
            return self.entdef_lines(kids[0], n)
        if kids and not s.is_and:
            self.warn.append(f"composite '{self.nm(s)}' has no default transition")
        return []

    def trigger(self, t):
        if t.timeout:
            return "Timeout_id"
        if t.event:
            return f"{cident(t.event)}_{self.pkg.name}_id"
        return "Null_id"

    def transitions(self, s, n, var):
        """if / else-if chain over the triggers of the transitions leaving s."""
        def group(ts, key):
            out = []
            for t in ts:
                k = key(t)
                for g in out:
                    if g[0] == k:
                        g[1].append(t)
                        break
                else:
                    out.append((k, [t]))
            return out

        sp = " " * n
        L = []
        for gi, (trig, ts) in enumerate(group(self.by_src.get(s, []), self.trigger)):
            L.append(sp + f"{'if' if gi == 0 else 'else if'} ({self.ev_test(trig)}) {{")
            if trig == "Timeout_id":
                for ti, (tid, tts) in enumerate(group(ts, lambda t: self.timeouts[t])):
                    L.append(sp + f"    {'if' if ti == 0 else 'else if'} ({self.tm_test(tid)}) {{")
                    L += self.guard_chain(tts, n + 8, var)
                    L.append(sp + "    }")
            else:
                e = self.ev.get(ts[0].event)
                if e is not None and e.args:
                    L += [sp + "    " + x for x in self.params_lines(e)]
                L += self.guard_chain(ts, n + 4, var)
            L.append(sp + "}")
        return L

    def guard_chain(self, ts, n, var):
        """First enabled transition wins; unguarded / else ones are tried last."""
        L = []
        ts = sorted(ts, key=lambda t: not t.guard.strip() or t.guard.strip() == "else")
        first = True
        for t in ts:
            g = self.ucode(t.guard)
            label = f"{self.tname(t.src)}>{self.tname(t.dst) if not t.internal else '(internal)'}"
            bare = first and (not g or g == "else")     # lone unguarded transition: no braces
            if g and g != "else":
                L.append(" " * n + f"{'if' if first else 'else if'} ({g}) {{")
            elif not bare:
                L.append(" " * n + "else {")
            k = n if bare else n + 4
            if t.internal:
                L += self.ublock(t.action, k, f"reaction {label}")
                L.append(" " * k + f"{var} = {self.YES};")
            else:
                L += self.complete("trans", t.src, t.dst, [t.action], k, label, var)
            if not bare:
                L.append(" " * n + "}")
            first = False
            if not g or g == "else":
                break
        return L

    # ---- dispatch: one nested switch -----------------------------------------
    def handles(self, s):
        """Does s or anything inside it react to events?"""
        return bool(self.by_src.get(s)) or any(self.handles(k) for k in s.children)

    def dispatch_lines(self, c, n, var):
        sp = " " * n
        L = []
        if c.is_and:
            for i, r in enumerate(c.children):
                if not self.handles(r):
                    continue
                rv = f"res_{r.cname}"
                L.append(sp + (f"if ({self.n}_isIn(me, {self.E(c)})) {{" if L else "{")
                         + f"    /* region {r.name} */")
                L.append(sp + f"    {self.STATUS} {rv} = {self.NO};")
                L += self.dispatch_lines(r, n + 4, rv)
                L.append(sp + f"    if ({rv} == {self.YES})")
                L.append(sp + f"        {var} = {self.YES};")
                L.append(sp + "}")
            return L
        kids = [k for k in c.children if self.handles(k)]
        if not kids:
            return L
        L.append(sp + f"switch ({self.sub(c)}) {{")
        for k in kids:
            L.append(sp + f"    case {self.E(k)}:")
            if composite(k):
                L += self.dispatch_lines(k, n + 8, var)
                if self.by_src.get(k):
                    L.append(sp + f"        if ({var} == {self.NO}) {{")
                    L += self.transitions(k, n + 12, var)
                    L.append(sp + "        }")
            else:
                L += self.transitions(k, n + 8, var)
            L.append(sp + "        break;")
        L += [sp + "    default:", sp + "        break;", sp + "}"]
        return L

    # ---- header -------------------------------------------------------------
    def header(self, events_h=None):
        n, c, m = self.n, self.c, self.m
        L = [BANNER.format(elem=n, file=f"{n}.h"), f"#ifndef {n}_H", f"#define {n}_H", "",
             '#include "RiCLite.h"']
        if events_h is None:
            L.append(f'#include "{self.pkg.name}.h"')
        L.append("")
        if events_h:
            L += events_h
        for a in c.assocs:
            L.append(f"struct {a.other};")
        if m:
            L += ["/*#[ ignore */", f"enum {n}_Enum {{", f"    {n}_RiCNonState = 0,"]
            L += [f"    {self.E(s)} = {i}," for i, s in enumerate(self.states[1:], 1)]
            L[-1] = L[-1].rstrip(",")
            L += ["};", "/*#]*/", ""]
        L += [f"/*## class {n} */", f"typedef struct {n} {n};", f"struct {n} {{"]
        if m:
            L.append("    RiCReactive ric_reactive;")
        for a in c.attributes:
            L.append(f"    {a.type} {a.name};\t\t/*## attribute {a.name} */")
        for a in c.assocs:
            L.append(f"    struct {a.other}* {a.name};\t\t/*## link {a.name} */")
        if m:
            L.append("    /*#[ ignore */")
            for s in self.states:
                if self.has_sub(s) and s.children:
                    L.append(f"    RhpInteger {s.cname}_subState;")
            for s in self.hist:
                L.append(f"    RhpInteger {s.cname}_lastState;")
            L.append("    /*#]*/")
        if not (m or c.attributes or c.assocs):
            L.append("    int dummy_;")
        L += ["};", ""]
        L.append(f"void {n}_Init({n}* const me{', RiCTask * p_task' if m else ''});")
        L.append(f"void {n}_Cleanup({n}* const me);")
        if m:
            L.append(f"RiCBoolean {n}_startBehavior({n}* const me);")
            L.append(f"int {n}_isIn(const {n}* const me, int state);")
            L.append("")
            L.append(f"/* IS_IN(me, {n}_<state>) */")
            for s in self.states[1:]:
                L.append(f"#define {n}_{s.cname}_IN(me) {n}_isIn((me), {self.E(s)})")
        if c.operations:
            L += ["", "/* Operations */"]
        for op in c.operations:
            if op.triggered:
                L.append(f"/*## triggered operation {op.name}() - handled right away (takeTrigger) */")
                L.append(f"void {n}_{op.name}({self.params(op)});")
            else:
                L.append(f"{op.ret} {n}_{op.name}({self.params(op)});")
        L += ["", "#endif", ""]
        return "\n".join(L)

    def params(self, op):
        return ", ".join([f"{self.n}* const me"] + [f"{a.type} {a.name}" for a in op.args])

    # ---- source -------------------------------------------------------------
    def source(self, events_c=None):
        n, c, m = self.n, self.c, self.m
        p = self.pkg.name
        L = [BANNER.format(elem=n, file=f"{n}.c"), f'#include "{n}.h"']
        L += [f'#include "{o}.h"' for o in sorted({a.other for a in c.assocs} - {n})]
        L.append("")
        if events_c:
            L += events_c
        L.append(f"/*## class {n} */")
        if m:
            L.append("/* lets action code write IS_IN(me, stateName) */")
            for s in self.states[1:]:
                L.append(f"#define {s.cname}_IN(me) {n}_isIn((me), {self.E(s)})")
            L.append("")
            tids = [tid for lst in self.timers_of.values() for tid, _ in lst]
            if tids:
                L.append("enum {")
                L += [f"    {v} = {i}," for i, v in enumerate(tids, 1)]
                L[-1] = L[-1].rstrip(",")
                L += ["};", ""]
            comps = [s for s in self.states[1:] if composite(s)]
            L += ["static void rootState_entDef(void * const void_me);",
                  "static RiCTakeEventStatus rootState_dispatchEvent(void * const void_me, RiCEventId id);"]
            if self.uses_term:
                L.append(f"static void rootState_exit({n}* const me);")
            for s in comps:
                L.append(f"static void {s.cname}_entDef({n}* const me);")
                if s in self.hist:
                    L.append(f"static void {s.cname}_histEntDef({n}* const me);")
                L.append(f"static void {s.cname}_exit({n}* const me);")
            L += ["", f"static const RiCReactive_Vtbl {n}_reactiveVtbl = {{",
                  "    rootState_dispatchEvent,", "    rootState_entDef,", f'    "{n}"', "};", ""]

        # Init / Cleanup
        L.append(f"void {n}_Init({n}* const me{', RiCTask * p_task' if m else ''}) {{")
        if self.pkg.events:
            L.append(f"    {p}_eventsInit();")
        if m:
            L.append(f"    RiCReactive_init(&me->ric_reactive, me, p_task, &{n}_reactiveVtbl);")
        for a in c.attributes:
            if a.default.strip():
                L.append(f"    me->{a.name} = {a.default};")
        for a in c.assocs:
            L.append(f"    me->{a.name} = NULL;")
        if m:
            for s in self.states:
                if self.has_sub(s) and s.children:
                    L.append(f"    {self.sub(s)} = {n}_RiCNonState;")
            for s in self.hist:
                L.append(f"    me->{s.cname}_lastState = {n}_RiCNonState;")
        if not (m or c.attributes or c.assocs or self.pkg.events):
            L.append("    (void)me;")
        L += self.ublock(c.init_body, 4, "operation Init()")
        L += ["}", "", f"void {n}_Cleanup({n}* const me) {{"]
        L.append("    RiCReactive_cleanup(&me->ric_reactive);" if m else "    (void)me;")
        L += ["}", ""]
        if m:
            L += [f"RiCBoolean {n}_startBehavior({n}* const me) {{",
                  "    return RiCReactive_startBehavior(&me->ric_reactive);", "}", ""]
            L += self.is_in()

        for op in c.operations:
            if op.triggered:
                en = cident(op.name)
                L += [f"/*## triggered operation {op.name}() */", f"void {n}_{op.name}({self.params(op)}) {{",
                      f"    {en} trigger;", f"    RiCEvent_init(&trigger.ric_event, {en}_{self.pkg.name}_id);",
                      "    trigger.ric_event.flags = 0;\t/* lives on the stack, not in the event pool */"]
                L += [f"    trigger.{a.name} = {a.name};" for a in op.args]
                L += ["    RiCReactive_takeTrigger(&me->ric_reactive, &trigger.ric_event);", "}", ""]
                continue
            L.append(f"/*## operation {op.name}() */")
            L.append(f"{op.ret} {n}_{op.name}({self.params(op)}) {{")
            if op.body.strip():
                L += [f"    /*#[ operation {op.name}() */", ind(op.body.strip(), 4), "    /*#]*/"]
            else:
                L.append("    (void)me;")
                if op.ret.strip() != "void":
                    L.append(f"    return ({op.ret})0;")
            L += ["}", ""]
        if not m:
            return "\n".join(L)

        # statechart
        L += ["/* ---- statechart ---- */", "",
              "static void rootState_entDef(void * const void_me) {", f"    {n} * const me = ({n} *)void_me;"]
        L += self.default_code(self.m.root, 4)
        L += ["}", "", "static RiCTakeEventStatus rootState_dispatchEvent(void * const void_me, RiCEventId id) {",
              f"    {n} * const me = ({n} *)void_me;", "    RiCTakeEventStatus res = eventNotConsumed;"]
        L += self.dispatch_lines(self.m.root, 4, "res")
        if self.by_src.get(self.m.root):
            L.append("    if (res == eventNotConsumed) {")
            L += self.transitions(self.m.root, 8, "res")
            L.append("    }")
        L += ["    return res;", "}", ""]
        if self.uses_term:
            L += [f"static void rootState_exit({n}* const me) {{"] + self.exit_body(self.m.root) + ["}", ""]
        for s in self.states[1:]:
            if composite(s):
                L += self.composite_funcs(s)
        return "\n".join(L)

    def is_in(self):
        n = self.n
        L = [f"int {n}_isIn(const {n}* const me, int state) {{", "    switch (state) {"]
        for s in self.states[1:]:
            conds, x = [], s
            while x.parent is not None:
                if not x.parent.is_and:
                    conds.insert(0, f"{self.sub(x.parent)} == {self.E(x)}")
                x = x.parent
            L.append(f"        case {self.E(s)}: return {' && '.join(conds) or '1'};")
        L += ["        default: return 0;", "    }", "}", ""]
        return L

    def exit_body(self, s):
        L = []
        if s in self.hist:
            L.append(f"    me->{s.cname}_lastState = {self.sub(s)};")
        if s.is_and:
            L += [f"    {r.cname}_exit(me);" for r in s.children]
        elif s.children:
            L.append(f"    switch ({self.sub(s)}) {{")
            for k in s.children:
                L.append(f"        case {self.E(k)}:")
                L += self.exit_lines(k, 12)
                L.append("            break;")
            L += ["        default:", "            break;", "    }"]
        return L

    def composite_funcs(self, s):
        n = self.n
        L = [f"/* {self.nm(s)} */", f"static void {s.cname}_entDef({n}* const me) {{"]
        L += self.enter_lines(s, 4)
        if s.is_and:
            for r in s.children:
                L += self.entdef_lines(r, 4)
        else:
            L += self.default_code(s, 4)
        L += ["}", ""]
        if s in self.hist:
            h = self.hist[s]
            L.append(f"static void {s.cname}_histEntDef({n}* const me) {{")
            L += self.enter_lines(s, 4)
            L.append(f"    switch (me->{s.cname}_lastState) {{")
            for k in s.children:
                L.append(f"        case {self.E(k)}:")
                L += self.entdef_lines(k, 12)
                L.append("            break;")
            L.append("        default:")
            if h.outgoing:
                L += self.complete("init", s, h.outgoing[0].dst, [h.outgoing[0].action], 12, f"{self.nm(s)}.H>default")
            else:
                L += self.default_code(s, 12)
            L += ["            break;", "    }", "}", ""]
        L.append(f"static void {s.cname}_exit({n}* const me) {{")
        L += self.exit_body(s)
        L += self.leave_lines(s, 4)
        L += ["}", ""]
        return L


