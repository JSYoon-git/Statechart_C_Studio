/* Statechart Studio - UI language. The UI is written in English; this file holds the Korean
   texts. _t("English {0}", x) returns the text in the current language with {0}, {1}, ...
   filled in. Static HTML: elements marked data-i18n (inner HTML) and every title attribute are
   translated by applyLanguage(); the editor re-renders its own panels with _t(). */
"use strict";

let LANG = (() => { try { return localStorage.getItem("scstudio.lang") || "en"; } catch (e) { return "en"; } })();

function _t(en, ...args) {
  let s = LANG === "ko" && Object.prototype.hasOwnProperty.call(KO, en) ? KO[en] : en;
  args.forEach((a, i) => { s = s.split(`{${i}}`).join(String(a)); });
  return s;
}

/* remember the English of the static page once, then show it in the current language */
function applyLanguage() {
  document.documentElement.lang = LANG;
  for (const el of document.querySelectorAll("[data-i18n]")) {
    if (el.dataset.en === undefined) el.dataset.en = el.innerHTML;
    el.innerHTML = LANG === "ko" && KO_HTML(el.dataset.en) != null ? KO_HTML(el.dataset.en) : el.dataset.en;
  }
  for (const el of document.querySelectorAll("[title], [data-tip]")) {
    if (el.dataset.enTitle === undefined) el.dataset.enTitle = el.getAttribute("title") || el.dataset.tip || "";
    const v = _t(el.dataset.enTitle);
    if (el.hasAttribute("title")) el.setAttribute("title", v); else el.dataset.tip = v;
  }
  const b = document.getElementById("bLang");
  if (b) b.textContent = LANG === "ko" ? "English" : "한국어";
}
/* the dictionary is keyed by the text as written in the HTML source (&gt; etc. decoded by the browser) */
function KO_HTML(en) {
  if (Object.prototype.hasOwnProperty.call(KO, en)) return KO[en];
  const plain = en.replace(/&gt;/g, ">").replace(/&lt;/g, "<").replace(/&amp;/g, "&");
  if (Object.prototype.hasOwnProperty.call(KO, plain)) return KO[plain];
  return null;
}
function setLanguage(lang) {
  LANG = lang;
  try { localStorage.setItem("scstudio.lang", lang); } catch (e) { /* ignore */ }
  applyLanguage();
}

