"""Task-style C emitter: a framework-free statechart module for a periodic MCU task.

Per class X the user gets X.h / X.c in C89 (ANSI C / C90, what MCU compilers share): /* */ comments
only, declarations at the top of a block, no designated initializers, no <stdbool.h>. They need
nothing but <stdint.h>, and no #define of their own (only the include guard):

    struct X { inputs; outputs; variables; links; state variables };
    void X_Init(X* const me, <type> c_a, ...);         once: config values (c_ parameters), other
                                                       variables' initial values, then startBehavior
    <ret> X_Main(X* const me, <type> i_a, ..., <type>* const o_b, ...);
                                                       every 10 ms task call: latch inputs,
                                                       user code (default X_takeTrigger(me);),
                                                       write outputs
    bool X_isIn(const X* const me, int state);

Rules (the user's design):
  * no events, no event queue, no timers: transitions are [guard]s only. An "event" is an input
    variable; a time is a variable the user counts (entry/ cnt = 0;  reaction/ cnt++;  [cnt >= 50])
  * X_takeTrigger: first the internal reactions of every active state (outer -> inner), then at
    most one transition (one per AND region), inner states first, by priority
  * inputs are X_Main parameters i_<name>; outputs: none -> void, one -> return value,
    several -> void + o_<name> pointer parameters (or X_In / X_Out structs)

    from task_c import generate
    files, warnings = generate(pkg, out_dir)
"""
import os
import re

from rhp_c import ClassGen, composite, ctype_kind, ind, is_region, user_code
from sc_ir import State

BANNER = """/*********************************************************************
\tGenerated by Statechart Studio (task-style C, no framework)
\tModel Element\t: {elem}
\tFile\t\t: {file}
*********************************************************************/
"""
TARGET_MAIN = "main.c"           # example: how the 10 ms task calls the modules
TASK_MS = 10                     # every X_Main is called from the 10 ms task

_IS_IN = re.compile(r"\bIS_IN\s*\(\s*me\s*,\s*([A-Za-z_]\w*)\s*\)")
_IS_IN_ARG = re.compile(r"\bIS_IN\s*\(\s*me\s*,$")          # IS_IN(me, <state>): a state, not a variable
_TOKENS = re.compile(r"""(/\*.*?\*/|//[^\n]*|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')|([A-Za-z_]\w*)""", re.S)


def vars_to_me(code, names):
    """`count++` -> `me->count++` for the class's variables; leaves strings, comments,
    `me->count`, `x.count` and `p->count` alone."""
    if not names or not code:
        return code

    def sub(m):
        if m.group(1) or m.group(2) not in names:
            return m.group(0)
        before = code[:m.start()].rstrip()
        if before.endswith((".", "->")) or _IS_IN_ARG.search(before):
            return m.group(0)
        return "me->" + m.group(2)
    return _TOKENS.sub(sub, code)


def zero_of(t):
    t = t.strip()
    if t == "bool":
        return "false"
    if ctype_kind(t) == "f":
        return "0.0f" if t == "float" else "0.0"
    if "*" in t:
        return "NULL"
    return "0"


class TaskGen(ClassGen):
    YES, NO, STATUS = "true", "false", "bool"

    def __init__(self, pkg, cls):
        super().__init__(pkg, cls)
        self.ins = [a for a in cls.attributes if a.dir == "in"]
        self.outs = [a for a in cls.attributes if a.dir == "out"]
        self.cfgs = [a for a in cls.attributes if a.dir == "config"]      # set by X_Init(me, c_...)
        self.names = {a.name for a in cls.attributes}
        self.struct = bool(getattr(cls, "io_struct", False))     # X_Main(me, const X_In*, X_Out*)
        self.warned_params = False
        self.errors = []
        self.timers_of = {}
        self.by_name = {}
        if self.m:
            for s in self.states[1:]:
                self.by_name.setdefault(s.name, []).append(s)
            for t in self.m.transitions:
                if t.timeout:
                    where = t.src.name if isinstance(t.src, State) else t.src.kind
                    self.errors.append(f"{self.n}: tm({t.timeout}) on '{where}' — there is no tm(); count with a variable "
                                       f"(entry/ cnt = 0;  reaction/ cnt++;  transition [cnt >= 50u])")

    # ---- hooks of ClassGen ----------------------------------------------------
    def ucode(self, code):
        code = user_code(code)                          # IS_IN(x) -> IS_IN(me, x)
        if "params->" in code and not self.warned_params:
            self.warned_params = True
            self.warn.append("params->... is an event argument — there are no events, use input variables")
        code = vars_to_me(code, self.names)

        def is_in(m):                                   # no macro: the plain function call
            hit = self.by_name.get(m.group(1), [])
            return f"{self.n}_isIn(me, {self.E(hit[0])})" if len(hit) == 1 else m.group(0)
        return _IS_IN.sub(is_in, code)

    def trace_trans(self, label):
        return f"/*## transition {label} */"

    def trace_state(self, kind, name):
        return ""

    def terminate_line(self):
        return "/* terminated: no state is active any more */"

    def none(self):
        return f"{self.n}_NonState"

    def enter_lines(self, s, n):
        if is_region(s):
            return []
        sp = " " * n
        L = []
        if not s.parent.is_and:
            L.append(sp + f"{self.sub(s.parent)} = {self.E(s)};")
        L += self.ublock(s.entry, n, f"state {self.nm(s)}.(Entry)")
        return L

    def leave_lines(self, s, n):
        if is_region(s):
            return []
        sp = " " * n
        L = self.ublock(s.exit, n, f"state {self.nm(s)}.(Exit)")
        if not s.parent.is_and:
            L.append(sp + f"{self.sub(s.parent)} = {self.none()};")
        return L

    def cond(self, t):
        parts = []
        if t.event:          # left over from an event trigger: an input / function the guard reads
            parts.append(self.ucode(t.event))
        g = self.ucode(t.guard)
        if g and g != "else":
            parts.append(f"({g})" if parts else g)
        return " && ".join(parts)

    def transitions(self, s, n, var):
        """First enabled transition wins, in priority order (the editor's prio, else drawing
        order); an unconditioned one is tried last. (Internal reactions are not here: they all
        run before the transitions, see reaction_lines.)"""
        sp = " " * n
        real = [t for t in self.by_src.get(s, []) if not t.internal]
        items = [(self.cond(t), t) for t in real]
        free = [x for x in items if not x[0]]
        if len(free) > 1:
            self.warn.append(f"'{self.nm(s)}' has {len(free)} transitions without a guard; only "
                             f"'{self.tname(free[0][1].src)}>{self.tname(free[0][1].dst)}' can ever fire")
        items = [x for x in items if x[0]] + free[:1]
        L = []
        for i, (c, t) in enumerate(items):
            label = f"{self.tname(t.src)}>{self.tname(t.dst)}"
            if c:
                L.append(sp + f"{'if' if i == 0 else 'else if'} ({c}) {{")
            else:
                L.append(sp + ("{" if i == 0 else "else {"))
            L += self.complete("trans", t.src, t.dst, [t.action], n + 4, label, var)
            L.append(sp + "}")
        return L

    def handles(self, s):
        """Does s or anything inside it have a transition (reactions are handled separately)?"""
        return any(not t.internal for t in self.by_src.get(s, [])) or any(self.handles(k) for k in s.children)

    # ---- internal reactions: every active state, outer -> inner, before the transitions ----
    def reacts(self, s):
        return [t for t in self.by_src.get(s, []) if t.internal]

    def has_reactions(self, s):
        return bool(self.reacts(s)) or any(self.has_reactions(k) for k in s.children)

    def own_reaction_lines(self, s, n):
        L = []
        for t in self.reacts(s):
            c, lbl = self.cond(t), f"reaction {self.tname(t.src)}"
            if c:
                L.append(" " * n + f"if ({c}) {{")
                L += self.ublock(t.action, n + 4, lbl)
                L.append(" " * n + "}")
            else:
                L += self.ublock(t.action, n, lbl)
        return L

    def reaction_lines(self, c, n):
        sp = " " * n
        L = []
        if c.is_and:
            for r in c.children:
                if self.has_reactions(r):
                    L += self.reaction_lines(r, n)
            return L
        kids = [k for k in c.children if self.has_reactions(k)]
        if not kids:
            return L
        L.append(sp + f"switch ({self.sub(c)}) {{")
        for k in kids:
            L.append(sp + f"    case {self.E(k)}:")
            L += self.own_reaction_lines(k, n + 8)
            if composite(k):
                L += self.reaction_lines(k, n + 8)
            L.append(sp + "        break;")
        L += [sp + "    default:", sp + "        break;", sp + "}"]
        return L

    def is_in(self):
        n = self.n
        L = [f"bool {n}_isIn(const {n}* const me, int state) {{", "    bool res;", "    switch (state) {"]
        for s in self.states[1:]:
            L.append(f"        case {self.E(s)}:")
            L.append(f"            res = {self.active_cond(s)};")
            L.append("            break;")
        L += ["        default:", "            res = false;", "            break;", "    }", "    return res;", "}", ""]
        return L

    def active_cond(self, s):
        conds, x = [], s
        while x.parent is not None:
            if not x.parent.is_and:
                conds.insert(0, f"({self.sub(x.parent)} == {self.E(x)})")
            x = x.parent
        return " && ".join(conds) or "true"

    # ---- signature --------------------------------------------------------------
    # two styles, chosen per class:
    #   parameters: X_Main(me, i_a, i_b, ...)  outputs: none -> void, one -> return, more -> o_ pointers
    #   structs:    X_Main(me, const X_In* const in, X_Out* const out)   (a pointer only when there
    #               are inputs / outputs) - fewer arguments when there are many
    def main_params(self):
        if self.struct:
            return ([f"const {self.n}_In* const in"] if self.ins else []) + ([f"{self.n}_Out* const out"] if self.outs else [])
        ps = [f"{a.type} i_{a.name}" for a in self.ins]
        if len(self.outs) > 1:
            ps += [f"{a.type}* const o_{a.name}" for a in self.outs]
        return ps

    def main_ret(self):
        return self.outs[0].type if len(self.outs) == 1 and not self.struct else "void"

    def call(self, me, ins, outs, _unused=""):
        """Lines that call X_Main in parameter style. ins: {name: C expression}; outs: {name: lvalue}."""
        n = self.n
        args = [me] + [ins[a.name] for a in self.ins]
        if len(self.outs) == 1:
            o = outs.get(self.outs[0].name)
            return [f"{o} = {n}_Main({', '.join(args)});" if o else f"(void){n}_Main({', '.join(args)});"]
        args += [f"&{outs[a.name]}" if a.name in outs else "NULL" for a in self.outs]
        return [f"{n}_Main({', '.join(args)});"]

    def init_sig(self):
        ps = [f"{self.n}* const me"] + [f"{a.type} c_{a.name}" for a in self.cfgs]
        return f"void {self.n}_Init({', '.join(ps)})"

    def main_sig(self):
        return f"{self.main_ret()} {self.n}_Main({', '.join([f'{self.n}* const me'] + self.main_params())})"

    def default_main_body(self):
        return f"{self.n}_takeTrigger(me);" if self.m else ""

    def state_int(self):
        return "uint8_t" if len(self.states) < 255 else "uint16_t"

    # ---- header ---------------------------------------------------------------
    def header(self, types=None):
        n, c, m = self.n, self.c, self.m
        L = [BANNER.format(elem=n, file=f"{n}.h"), f"#ifndef {n}_H", f"#define {n}_H", "",
             "#include <stdint.h>", "",
             "/* C89 has no <stdbool.h>: bool is a byte, false / true are enumeration constants.",
             " * Written once however many of these headers are included (a guard like the header",
             " * guard), and skipped when <stdbool.h> was included first. */",
             "#ifndef __bool_true_false_are_defined",
             "#ifndef STATECHART_BOOL",
             "#define STATECHART_BOOL",
             "typedef uint8_t bool;",
             "enum { false = 0, true = 1 };",
             "#endif",
             "#endif"]
        if types is None:
            L.append(f'#include "{self.pkg.name}.h"')
        elif types:
            L += ["", "/* types */"] + types
        L.append("")
        if m:
            L += [f"enum {n}_Enum {{", f"    {n}_NonState = 0,"]
            L += [f"    {self.E(s)} = {i}," for i, s in enumerate(self.states[1:], 1)]
            L[-1] = L[-1].rstrip(",")
            L += ["};", ""]
        for a in c.assocs:
            L.append(f"struct {a.other};")
        if self.struct:
            for kind, attrs, what in (("In", self.ins, "inputs"), ("Out", self.outs, "outputs")):
                if attrs:
                    L += [f"/* {what} of {n}_Main() */", "typedef struct {"]
                    L += [f"    {a.type} {a.name};" for a in attrs]
                    L += [f"}} {n}_{kind};", ""]
        L += [f"typedef struct {n} {n};", f"struct {n} {{"]
        groups = [("inputs (latched at the start of " + n + "_Main)", self.ins),
                  ("outputs (handed out at the end of " + n + "_Main)", self.outs),
                  ("configuration (set once by " + n + "_Init)", self.cfgs),
                  ("variables", [a for a in c.attributes if a.dir not in ("in", "out", "config")])]
        for title, attrs in groups:
            if attrs:
                L.append(f"    /* {title} */")
                L += [f"    {a.type} {a.name};" for a in attrs]
        for a in c.assocs:
            L.append(f"    struct {a.other}* {a.name};")
        if m:
            si = self.state_int()
            L.append("    /* states */")
            for s in self.states:
                if self.has_sub(s) and s.children:
                    L.append(f"    {si} {s.cname}_subState;")
            for s in self.hist:
                L.append(f"    {si} {s.cname}_lastState;")
        if not (m or c.attributes or c.assocs):
            L.append("    uint8_t dummy_;")
        L += ["};", "", f"{self.init_sig()};", f"{self.main_sig()};"]
        if m:
            L.append(f"bool {n}_isIn(const {n}* const me, int state);")
        for op in c.operations:
            L.append(f"{op.ret} {n}_{op.name}({self.params(op)});")
        L += ["", "#endif", ""]
        return "\n".join(L)

    # ---- source ---------------------------------------------------------------
    def source(self):
        n, c, m = self.n, self.c, self.m
        L = [BANNER.format(elem=n, file=f"{n}.c"), f'#include "{n}.h"']
        L += [f'#include "{o}.h"' for o in sorted({a.other for a in c.assocs} - {n})]
        L.append("")
        reactions = bool(m) and self.has_reactions(self.m.root)
        if m:
            L += [f"static void {n}_startBehavior({n}* const me);",
                  f"static void {n}_takeTrigger({n}* const me);",
                  f"static void rootState_entDef({n}* const me);",
                  f"static bool rootState_dispatch({n}* const me);"]
            if reactions:
                L.append(f"static void rootState_reactions({n}* const me);")
            if self.uses_term:
                L.append(f"static void rootState_exit({n}* const me);")
            for s in self.states[1:]:
                if composite(s):
                    L.append(f"static void {s.cname}_entDef({n}* const me);")
                    if s in self.hist:
                        L.append(f"static void {s.cname}_histEntDef({n}* const me);")
                    L.append(f"static void {s.cname}_exit({n}* const me);")
            L.append("")

        # Init
        L.append(f"{self.init_sig()} {{")
        for a in c.attributes:
            if a.dir == "config":
                L.append(f"    me->{a.name} = c_{a.name};")
            else:
                L.append(f"    me->{a.name} = {a.default.strip() or zero_of(a.type)};")
        for a in c.assocs:
            L.append(f"    me->{a.name} = NULL;")
        if m:
            for s in self.states:
                if self.has_sub(s) and s.children:
                    L.append(f"    {self.sub(s)} = {self.none()};")
            for s in self.hist:
                L.append(f"    me->{s.cname}_lastState = {self.none()};")
        L += self.ublock(c.init_body, 4, "operation Init()")
        if m:
            L.append(f"    {n}_startBehavior(me);")
        if not (m or c.attributes or c.assocs or c.init_body.strip()):
            L.append("    me->dummy_ = 0u;")
        L += ["}", ""]

        # Main
        L += [f"{self.main_sig()} {{"]
        if self.ins:
            if self.struct:
                L.append("    if (in != NULL) {")
                L += [f"        me->{a.name} = in->{a.name};" for a in self.ins]
                L.append("    }")
            else:
                L += [f"    me->{a.name} = i_{a.name};" for a in self.ins]
        body = self.c.main_body if self.c.main_body is not None else self.default_main_body()
        L.append("    /*#[ operation Main() */")
        if body.strip():
            L.append(ind(self.ucode(body).strip(), 4))
        L.append("    /*#]*/")
        if self.struct:
            if self.outs:
                L.append("    if (out != NULL) {")
                L += [f"        out->{a.name} = me->{a.name};" for a in self.outs]
                L.append("    }")
        elif len(self.outs) == 1:
            L.append(f"    return me->{self.outs[0].name};")
        else:
            for a in self.outs:
                L += [f"    if (o_{a.name} != NULL) {{", f"        *o_{a.name} = me->{a.name};", "    }"]
        if not (self.ins or self.outs or body.strip()):
            L.append("    (void)me;")
        L += ["}", ""]

        if m:
            L += self.is_in()

        for op in c.operations:
            L.append(f"{op.ret} {n}_{op.name}({self.params(op)}) {{")
            if op.body.strip():
                L += [f"    /*#[ operation {op.name}() */", ind(op.body.strip(), 4), "    /*#]*/"]
            else:
                L.append("    (void)me;")
                if op.ret.strip() != "void":
                    L.append(f"    return ({op.ret})0;")
            L += ["}", ""]
        if not m:
            return "\n".join(L)

        # statechart
        L += [f"static void {n}_startBehavior({n}* const me) {{", "    rootState_entDef(me);", "}", "",
              "/* one step: the internal reactions of the active states, then at most one transition */",
              f"static void {n}_takeTrigger({n}* const me) {{"]
        if reactions:
            L.append("    rootState_reactions(me);")
        L += ["    (void)rootState_dispatch(me);", "}", "",
              f"static void rootState_entDef({n}* const me) {{"]
        L += self.default_code(self.m.root, 4) or ["    (void)me;"]
        L += ["}", ""]
        if reactions:
            L += [f"static void rootState_reactions({n}* const me) {{"]
            L += self.reaction_lines(self.m.root, 4)
            L += ["}", ""]
        L += [f"static bool rootState_dispatch({n}* const me) {{", "    bool res = false;"]
        L += self.dispatch_lines(self.m.root, 4, "res")
        if any(not t.internal for t in self.by_src.get(self.m.root, [])):
            L.append("    if (!res) {")
            L += self.transitions(self.m.root, 8, "res")
            L.append("    }")
        L += ["    return res;", "}", ""]
        if self.uses_term:
            L += [f"static void rootState_exit({n}* const me) {{"] + self.exit_body(self.m.root) + ["}", ""]
        for s in self.states[1:]:
            if composite(s):
                L += self.composite_funcs(s)
        return "\n".join(L)


