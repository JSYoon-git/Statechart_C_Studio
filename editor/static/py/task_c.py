def type_lines(pkg):
    return [t if t.rstrip().endswith((";", "}")) or t.lstrip().startswith("#") else t + ";" for t in pkg.types]


def target_main(pkg, gens):
    """Example: X_Init once, X_Main from the 10 ms task. Inputs / outputs are plain variables."""
    L = [BANNER.format(elem=pkg.name, file=TARGET_MAIN)]
    L += [f'#include "{g.n}.h"' for g in gens]
    L.append("")

    def init(a):
        return a.default.strip() or zero_of(a.type)
    for g in gens:
        L.append(f"static {g.n} its{g.n};")
        if g.struct:
            for kind, attrs in (("in", g.ins), ("out", g.outs)):
                if attrs:
                    vals = ", ".join(init(a) for a in attrs)          # positional: C89 has no .name = 
                    L.append(f"static {g.n}_{kind.capitalize()} io_{g.n}_{kind} = {{ {vals} }};")
            continue
        for a in g.ins + g.outs:
            L.append(f"static {a.type} io_{g.n}_{a.name} = {init(a)};")
    L += ["", f"/* {TASK_MS} ms task */", f"void Task_{TASK_MS}ms(void) {{"]
    for g in gens:
        if g.struct:
            args = [f"&its{g.n}"] + ([f"&io_{g.n}_in"] if g.ins else []) + ([f"&io_{g.n}_out"] if g.outs else [])
            L.append(f"    {g.n}_Main({', '.join(args)});")
            continue
        L += ["    " + x for x in g.call(f"&its{g.n}", {a.name: f"io_{g.n}_{a.name}" for a in g.ins},
                                     {a.name: f"io_{g.n}_{a.name}" for a in g.outs}, "")]
    L += ["}", "", "int main(void) {"]
    for g in gens:      # config values: the initial values from the drawing, change them here
        if len(g.cfgs) <= 1:
            args = [f"&its{g.n}"] + [f"{a.default.strip() or zero_of(a.type)} /* {a.name} */" for a in g.cfgs]
            L.append(f"    {g.n}_Init({', '.join(args)});")
            continue
        pad = " " * (len(g.n) + 10)
        rows = [f"&its{g.n}"] + [f"{a.default.strip() or zero_of(a.type)}" for a in g.cfgs]
        names = [""] + [a.name for a in g.cfgs]
        L.append(f"    {g.n}_Init({rows[0]},")
        for i in range(1, len(rows)):
            last = i == len(rows) - 1
            L.append(f"{pad}{rows[i]}{');' if last else ','}\t/* {names[i]} */")
    for g in gens:
        for a in g.c.assocs:
            if any(x.n == a.other for x in gens):
                L.append(f"    its{g.n}.{a.name} = &its{a.other};")
    L += ["    for (;;) {", f"        Task_{TASK_MS}ms();\t/* every {TASK_MS} ms */", "    }", "}", ""]
    return "\n".join(L)


def generate(pkg, out):
    """Write the sources to `out` and return ({file: text}, warnings):
    X.c / X.h per class, <Pkg>.h when several classes share types, and the example main.c."""
    os.makedirs(out, exist_ok=True)
    single = len(pkg.classes) == 1
    tl = type_lines(pkg)
    files = {}
    if not single and tl:
        p = pkg.name
        files[f"{p}.h"] = "\n".join([BANNER.format(elem=p, file=f"{p}.h"), f"#ifndef {p}_H", f"#define {p}_H", "",
                                     "/* types shared by the classes */"] + tl + ["", "#endif", ""])
    warnings = list(pkg.warnings)
    gens = [TaskGen(pkg, c) for c in pkg.classes]
    errors = [e for g in gens for e in g.errors]
    if errors:
        raise ValueError("errors — " + " / ".join(errors))
    for g in gens:
        files[f"{g.n}.h"] = g.header(tl if single or not tl else None)
        files[f"{g.n}.c"] = g.source()
        warnings += [f"{g.n}: {w}" for w in g.warn]
    files[TARGET_MAIN] = target_main(pkg, gens)
    for fn, text in files.items():
        with open(os.path.join(out, fn), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    return files, warnings
