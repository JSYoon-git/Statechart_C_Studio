"""Unit-test scenarios (step tables) of the example projects. build_examples.py stores them in each
example JSON as "scenarios"; the editor's Scenario tab shows and runs them (see ../scenario.py).

A step:  S(n, set, expect, init=False)
  n       10 ms task calls (0 = only check)      set     inputs that change before the calls (they stay)
  init    True = X_Init again first (inputs / variables back to their initial values); config values
          (X_Init parameters) can be given in `set` on such a row
  expect  checked after the calls: OUTPUTS only, name=value / name>=value ...  (Class.name with several classes).
          States and internal variables are not checked: the drawing shows the states while a scenario runs

Timing of the generated code: internal reactions (cnt++) run first, then one transition. A state entered
in call k with `cnt = 0` and a guard [cnt >= N] is left in call k + N.
"""


def S(n, set_="", expect="", init=False):
    d = {"n": n, "set": set_, "expect": expect}
    if init:
        d["init"] = True               # X_Init is called again first (config values may be set on this row)
    return d


def sc(name, *steps):
    return {"name": name, "steps": list(steps)}


